'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const listeners = {};
const nodes = {};
const makeNode = () => ({textContent:'',style:{},dataset:{},attributes:{},classList:{add(){},remove(){}},setAttribute(k,v){this.attributes[k]=v},querySelector(){return makeNode()},hasAttribute(){return false},offsetWidth:1});
for (const id of ['st-tip-goal', 'st-goal-title', 'st-goal-current', 'st-goal-target','st-goal-percent','st-goal-fill']) nodes[id]=makeNode();
const goalbar = makeNode(); nodes['st-tip-goal'].querySelector=()=>goalbar;
const document={getElementById:id=>nodes[id]||null,addEventListener:(type,fn)=>{listeners[type]=fn}};
const source=fs.readFileSync('streamlabs-tip-goal/JS.txt','utf8').replace('%%ANIMATION%%','shine');
vm.runInNewContext(source,{document,Number,Math,String,setTimeout,clearTimeout});
assert.equal(typeof listeners.goalLoad,'function');
assert.equal(typeof listeners.goalEvent,'function');
listeners.goalLoad({detail:{title:'STREAM COSTS',amount:{current:50,target:200}}});
assert.equal(nodes['st-goal-current'].textContent,'$50.00');
assert.equal(nodes['st-goal-target'].textContent,'$200.00');
assert.equal(nodes['st-goal-fill'].style.width,'25.000%');
assert.equal(goalbar.attributes['aria-valuenow'],'25');
listeners.goalEvent({detail:{title:'STREAM COSTS',amount:{current:500,target:200}}});
assert.equal(nodes['st-goal-fill'].style.width,'100.000%');
listeners.goalEvent({detail:{title:'STREAM COSTS',amount:{current:9,target:0}}});
assert.equal(nodes['st-goal-fill'].style.width,'0.000%');
listeners.goalEvent({detail:{amount:{current:'not numeric',target:0}}});
assert.equal(nodes['st-goal-fill'].style.width,'0.000%');
console.log('Streamlabs Tip Goal custom event adapter checks passed');